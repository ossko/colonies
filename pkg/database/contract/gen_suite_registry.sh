#!/usr/bin/env bash
# Regenerates suite_registry.go: the explicit registration of every
# conformance test in this package. Run after adding tests:
#
#   ./gen_suite_registry.sh
#
# NOTE: go test only discovers Test functions in the package under test, so
# the contract package's tests cannot be discovered implicitly; the registry
# makes them runnable via RunSuite (drivers: func TestConformance(t *testing.T) {
# contract.RunSuite(t) }).
set -euo pipefail
cd "$(dirname "$0")"

{
	echo "// Code generated by gen_suite_registry.sh; DO NOT EDIT."
	echo "// Run ./gen_suite_registry.sh after adding conformance tests."
	echo ""
	echo "package contract"
	echo ""
	echo "func init() {"
	for f in *_suite.go; do
		grep -hE '^func Test[A-Za-z0-9_]+\(' "$f" \
			| sed -E 's/^func (Test[A-Za-z0-9_]+)\(.*/\tregisterSuiteTest("\1", \1)/'
	done | sort
	echo "}"
} > suite_registry.go

echo "suite_registry.go: $(grep -c registerSuiteTest suite_registry.go) tests registered"
