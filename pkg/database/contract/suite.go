// Package contract contains the behavioral (conformance) test suite that
// defines a correct database driver implementation. It is the executable
// companion of CONTRACT.md: every driver must pass this suite in full.
//
// The tests in this package are plain .go files on purpose (not _test.go):
// they carry no driver code themselves and are included only in the test
// binaries of driver packages. A driver activates the suite by registering
// a ConformanceFactory from an init() in one of its *_test.go files, e.g.:
//
//	// pkg/database/postgresql/conformance_test.go
//	func init() {
//		contract.RegisterConformanceFactory(func(prefix string) (database.Database, error) {
//			return PrepareTestsWithPrefix(prefix)
//		})
//	}
//
// Then `go test ./pkg/database/postgresql/` runs the driver-specific tests
// AND the full conformance suite. Exactly one driver factory may be
// registered per test binary.
//
// See CONTRACT.md for the semantics verified here.
package contract

import (
	"testing"

	"github.com/colonyos/colonies/pkg/database"
)

// ConformanceFactory prepares a connected database with an empty schema and
// the given table prefix, à la database.Database. The driver owns the whole
// lifecycle (selection of the backend, connection, schema) so that the
// suite measures only behavior.
type ConformanceFactory func(prefix string) (database.Database, error)

var conformanceFactory ConformanceFactory

// RegisterConformanceFactory activates the conformance suite for the
// registering driver. Panics on nil or duplicate registration.
func RegisterConformanceFactory(factory ConformanceFactory) {
	if factory == nil {
		panic("contract: RegisterConformanceFactory called with nil factory")
	}
	if conformanceFactory != nil {
		panic("contract: conformance factory already registered (one driver per test binary)")
	}
	conformanceFactory = factory
}

// suiteTest is a single behavioral test of the conformance suite.
type suiteTest struct {
	name string
	fn   func(t *testing.T)
}

var suiteTests []suiteTest

// registerSuiteTest is called from suite_registry.go (generated by
// gen_suite_registry.sh). Add tests by writing func TestX(t *testing.T) in a
// *_suite.go file, then regenerate the registry.
func registerSuiteTest(name string, fn func(t *testing.T)) {
	for _, existing := range suiteTests {
		if existing.name == name {
			panic("contract: duplicate suite test: " + name)
		}
	}
	suiteTests = append(suiteTests, suiteTest{name: name, fn: fn})
}

// RunSuite runs every conformance test as a subtest of t. Drivers invoke it
// from a single Test function in their own package:
//
//	func TestConformance(t *testing.T) { contract.RunSuite(t) }
//
// Individual tests can be selected with go test -run
// TestConformance/<TestName>.
func RunSuite(t *testing.T) {
	if conformanceFactory == nil {
		t.Fatal("contract: no conformance driver registered")
	}
	tests := make([]suiteTest, len(suiteTests))
	copy(tests, suiteTests)
	for i := range tests {
		for j := i + 1; j < len(tests); j++ {
			if tests[j].name < tests[i].name {
				tests[i], tests[j] = tests[j], tests[i]
			}
		}
	}
	for _, st := range tests {
		st := st
		t.Run(st.name, st.fn)
	}
}

// PrepareTests returns a connected, empty database with the default prefix.
func PrepareTests() (database.Database, error) {
	return PrepareTestsWithPrefix("TEST_")
}

// PrepareTestsWithPrefix returns a connected, empty database with the given
// prefix. Prefixes isolate parallel tests and processes from each other
// (CONTRACT.md §7).
func PrepareTestsWithPrefix(prefix string) (database.Database, error) {
	if conformanceFactory == nil {
		panic("contract: no conformance driver registered; run the suite from a driver " +
			"package that has registered a factory (e.g. go test ./pkg/database/postgresql/)")
	}
	return conformanceFactory(prefix)
}
